TEST(round_trips_a_png) {
  const auto in = vec(kPng, kPng_len);
  std::vector<uint8_t> payload, back;
  CHECK_MSG(png_unpack(in, payload), "declined a valid PNG");
  CHECK_MSG(png_repack(payload, back), "repack failed");
  CHECK_MSG(back == in, "round-trip is not byte-exact");
}

TEST(the_payload_carries_the_inflated_image) {
  const auto in = vec(kPng, kPng_len);
  std::vector<uint8_t> payload;
  CHECK_MSG(png_unpack(in, payload), "declined a valid PNG");
  // 48x48 RGB with a filter byte per row: the inflated scanlines alone are 6,960 bytes,
  // far more than the compressed chunk, which is the whole point of the transform.
  CHECK_MSG(payload.size() > 6000, "payload does not contain the inflated scanlines");
}

TEST(declines_non_png) {
  const std::string prose = "\x89PNG is mentioned here but this is text, not an image.";
  std::vector<uint8_t> payload;
  CHECK_MSG(!png_unpack(vec(reinterpret_cast<const uint8_t*>(prose.data()), prose.size()),
                        payload),
            "accepted prose as a PNG");
}

TEST(declines_a_truncated_png) {
  auto in = vec(kPng, kPng_len);
  in.resize(in.size() - 20);
  std::vector<uint8_t> payload;
  CHECK_MSG(!png_unpack(in, payload), "accepted a truncated PNG");
}

TEST(repack_rejects_a_damaged_payload) {
  const auto in = vec(kPng, kPng_len);
  std::vector<uint8_t> payload, back;
  CHECK_MSG(png_unpack(in, payload), "declined a valid PNG");

  auto truncated = payload;
  truncated.resize(truncated.size() - 8);
  CHECK_MSG(!png_repack(truncated, back), "accepted a truncated payload");
}

TEST(packing_is_deterministic) {
  const auto in = vec(kPng, kPng_len);
  std::vector<uint8_t> a, b;
  CHECK_MSG(png_unpack(in, a), "declined a valid PNG");
  CHECK_MSG(png_unpack(in, b), "declined a valid PNG");
  CHECK_MSG(a == b, "packing the same input twice gave different bytes");
}

