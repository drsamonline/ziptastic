// A 512-byte POSIX tar header, so a member can be placed 512 bytes into a buffer the way a
// real tar does it.
void put_tar_header(std::vector<uint8_t>& out, const std::string& name, size_t size) {
  std::vector<uint8_t> h(512, 0);
  std::memcpy(&h[0], name.data(), std::min<size_t>(name.size(), 100));
  std::snprintf(reinterpret_cast<char*>(&h[100]), 8, "%07o", 0644);
  std::snprintf(reinterpret_cast<char*>(&h[108]), 8, "%07o", 0);
  std::snprintf(reinterpret_cast<char*>(&h[116]), 8, "%07o", 0);
  std::snprintf(reinterpret_cast<char*>(&h[124]), 12, "%011o", static_cast<unsigned>(size));
  std::snprintf(reinterpret_cast<char*>(&h[136]), 12, "%011o", 0);
  std::memset(&h[148], ' ', 8);  // the checksum field counts as spaces
  h[156] = '0';                  // regular file
  std::memcpy(&h[257], "ustar", 6);
  h[263] = '0';
  h[264] = '0';
  unsigned sum = 0;
  for (uint8_t b : h) sum += b;
  std::snprintf(reinterpret_cast<char*>(&h[148]), 8, "%06o", sum);
  out.insert(out.end(), h.begin(), h.end());
}

CompressOptions precomp_on() {
  CompressOptions opt;
  opt.precomp = true;
  opt.block_size = 64 * 1024;
  return opt;
}

// The transform fired and the bytes come back: both halves, every time.
void expect_precomp_roundtrip(const std::vector<uint8_t>& input, const char* what) {
  std::vector<uint8_t> packed, back;
  CHECK_ERR(compress(input, packed, precomp_on(), nullptr), Err::Ok);
  CHECK_ERR(decompress(packed, back), Err::Ok);
  CHECK_MSG(back == input, std::string(what) + ": round trip mismatch");

  ByteReader r(packed);
  FileHeader fh;
  CHECK_ERR(read_file_header(r, fh), Err::Ok);
  CHECK_MSG((fh.flags & kFlagPrecomp) != 0,
            std::string(what) + ": precomp did not fire");
}

TEST(a_zip_with_data_descriptors_is_reached) {
  const auto zip = streamed_zip();
  // The local header's compressed size really is zero — that is the case under test, and
  // a fixture that stopped being streamed would silently stop testing anything.
  CHECK_EQ(zip[6] & 0x08, uint8_t{0x08});  // general purpose flag: data descriptor
  CHECK_EQ(zip[18], uint8_t{0});
  CHECK_EQ(zip[19], uint8_t{0});
  CHECK_EQ(zip[20], uint8_t{0});
  CHECK_EQ(zip[21], uint8_t{0});
  expect_precomp_roundtrip(zip, "streamed zip");
}

TEST(a_streamed_zip_inside_a_tar_is_reached) {
  const auto zip = streamed_zip();
  std::vector<uint8_t> tar;
  put_tar_header(tar, "inner.zip", zip.size());
  tar.insert(tar.end(), zip.begin(), zip.end());
  tar.resize(tar.size() + (512 - zip.size() % 512) % 512, 0);  // padding to the block
  tar.resize(tar.size() + 1024, 0);                            // the two end blocks
  expect_precomp_roundtrip(tar, "tar of a streamed zip");
}

// One stray local-header signature with an impossible length used to stop the scan dead,
// losing every member after it. A tar header, or the inside of a compressed member, is
// full of bytes that can look like one.
TEST(a_stray_local_header_signature_does_not_stop_the_scan) {
  std::vector<uint8_t> stuffed(40, 0);
  std::memcpy(stuffed.data(), "PK\x03\x04", 4);
  stuffed[8] = 8;                                        // "deflate"
  stuffed[18] = 0xFF;                                    // a compressed size that runs
  stuffed[19] = 0xFF;                                    // past the end of the buffer
  stuffed[20] = 0xFF;
  stuffed[21] = 0xFF;
  const auto zip = streamed_zip();
  stuffed.insert(stuffed.end(), zip.begin(), zip.end());
  expect_precomp_roundtrip(stuffed, "streamed zip behind a false header");
}

