TEST(round_trips_a_raw_cd_image) {
  const auto in = vec(kCdImage, kCdImage_len);
  std::vector<uint8_t> packed, back;
  CHECK_MSG(ecc_pack(in, packed), "declined a valid Mode 2 Form 1 image");
  CHECK_MSG(ecc_unpack(packed, back), "unpack failed");
  CHECK_MSG(back == in, "round-trip is not byte-exact");
}

TEST(the_payload_drops_the_parity) {
  const auto in = vec(kCdImage, kCdImage_len);
  std::vector<uint8_t> packed;
  CHECK_MSG(ecc_pack(in, packed), "declined a valid image");
  // Two sectors: 4,704 bytes in, 276 parity bytes each removed, plus two kind bytes and
  // a length varint.
  CHECK_MSG(packed.size() < in.size() - 500, "payload did not drop the parity");
}

TEST(declines_a_sector_whose_parity_is_wrong) {
  auto in = vec(kCdImage, kCdImage_len);
  in[2076] ^= 0xFF;  // first parity byte of the first sector
  std::vector<uint8_t> packed;
  CHECK_MSG(!ecc_pack(in, packed), "accepted a sector whose parity does not verify");
}

TEST(declines_non_cd_data) {
  const std::string prose = "This is not a disc image, it is a sentence about one.";
  std::vector<uint8_t> packed;
  CHECK_MSG(!ecc_pack(vec(reinterpret_cast<const uint8_t*>(prose.data()), prose.size()),
                      packed),
            "accepted prose as a disc image");
}

TEST(declines_a_partial_sector) {
  auto in = vec(kCdImage, kCdImage_len);
  in.resize(in.size() - 100);
  std::vector<uint8_t> packed;
  CHECK_MSG(!ecc_pack(in, packed), "accepted a file that is not a whole number of sectors");
}

TEST(unpack_rejects_a_damaged_payload) {
  const auto in = vec(kCdImage, kCdImage_len);
  std::vector<uint8_t> packed, back;
  CHECK_MSG(ecc_pack(in, packed), "declined a valid image");
  auto truncated = packed;
  truncated.resize(truncated.size() - 10);
  CHECK_MSG(!ecc_unpack(truncated, back), "accepted a truncated payload");
}

TEST(packing_is_deterministic) {
  const auto in = vec(kCdImage, kCdImage_len);
  std::vector<uint8_t> a, b;
  CHECK_MSG(ecc_pack(in, a), "declined a valid image");
  CHECK_MSG(ecc_pack(in, b), "declined a valid image");
  CHECK_MSG(a == b, "packing the same input twice gave different bytes");
}

// A payload may declare a sector count it does not carry. The output is 2352 bytes per
// sector, so the declaration sizes a large allocation: without the structural bound a
// 64 MB payload could declare 2^26 sectors and ask for 158 GB.
TEST(a_declared_sector_count_must_be_carried) {
  std::vector<uint8_t> packed;
  // varint for 2^26 sectors, then two kind bytes and nothing else.
  uint64_t sectors = uint64_t{1} << 26;
  while (sectors >= 0x80) {
    packed.push_back(static_cast<uint8_t>(sectors) | 0x80u);
    sectors >>= 7;
  }
  packed.push_back(static_cast<uint8_t>(sectors));
  packed.push_back(0);
  packed.push_back(0);

  std::vector<uint8_t> out;
  const auto started = std::chrono::steady_clock::now();
  const bool ok = ecc_unpack(packed, out);
  const auto ms = std::chrono::duration_cast<std::chrono::milliseconds>(
                      std::chrono::steady_clock::now() - started)
                      .count();
  CHECK_MSG(!ok, "accepted a sector count the payload does not carry");
  CHECK_MSG(out.empty(), "allocated from a declared sector count");
  CHECK_MSG(ms < 1000, "the refusal took long enough to have allocated 158 GB");
}

