TEST(round_trips_16_bit_stereo) {
  const auto in = vec(kWav, kWav_len);
  std::vector<uint8_t> packed, back;
  CHECK_MSG(wav_pack(in, packed), "declined a 16-bit stereo WAV");
  CHECK_MSG(packed.size() < in.size(), "transform did not shrink the data");
  CHECK_MSG(wav_unpack(packed, back), "unpack failed");
  CHECK_MSG(back == in, "round-trip is not byte-exact");
}

TEST(the_payload_is_smaller_than_the_samples) {
  const auto in = vec(kWav, kWav_len);
  std::vector<uint8_t> packed;
  CHECK_MSG(wav_pack(in, packed), "declined a 16-bit stereo WAV");
  // 300 stereo frames = 1200 bytes of samples; the delta stream must beat that.
  CHECK_MSG(packed.size() < 1200, "delta stream is not smaller than the samples");
}

TEST(declines_non_wav) {
  const std::string prose =
      "RIFF is mentioned here but this is not a WAV file at all, just text that "
      "happens to name the format in passing.";
  std::vector<uint8_t> packed;
  CHECK_MSG(!wav_pack({reinterpret_cast<const uint8_t*>(prose.data()), prose.size()}, packed),
            "accepted prose as a WAV");
}

TEST(declines_truncated_data_chunk) {
  auto in = vec(kWav, kWav_len);
  in.resize(in.size() - 40);  // cut into the sample data
  std::vector<uint8_t> packed;
  CHECK_MSG(!wav_pack(in, packed), "accepted a truncated data chunk");
}

TEST(unpack_rejects_a_damaged_payload) {
  const auto in = vec(kWav, kWav_len);
  std::vector<uint8_t> packed, back;
  CHECK_MSG(wav_pack(in, packed), "declined a 16-bit stereo WAV");

  auto truncated = packed;
  truncated.resize(truncated.size() - 6);
  CHECK_MSG(!wav_unpack(truncated, back), "accepted a truncated payload");

  auto wrong_magic = packed;
  wrong_magic[wrong_magic.size() - 1] = 'X';
  CHECK_MSG(!wav_unpack(wrong_magic, back), "accepted a wrong magic");
}

TEST(packing_is_deterministic) {
  const auto in = vec(kWav, kWav_len);
  std::vector<uint8_t> a, b;
  CHECK_MSG(wav_pack(in, a), "declined a 16-bit stereo WAV");
  CHECK_MSG(wav_pack(in, b), "declined a 16-bit stereo WAV");
  CHECK_MSG(a == b, "packing the same input twice gave different bytes");
}

